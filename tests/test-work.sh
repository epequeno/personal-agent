#!/usr/bin/env bash
# Acceptance test for bin/pa-work. Fixture trackers, no model calls, no network.
# Each case writes a tiny _Work.yaml and asserts validate's exit code / message.
set -uo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
pass=0; fail=0
ok()  { echo "  ok   $1"; pass=$((pass+1)); }
bad() { echo "  FAIL $1"; fail=$((fail+1)); }
check() { if eval "$2"; then ok "$1"; else bad "$1"; fi; }

W="$T/_Work.yaml"

# write <body> — wraps a body in the minimal envelope the parser requires
write() {
  { echo "meta:"; echo "  version: 1"; echo "  updated: 2026-10-09"
    echo "items:"; cat; } > "$W"
}

run() { "$HERE/bin/pa-work" validate --file "$W" >"$T/out" 2>"$T/err"; echo $?; }

# ---------------------------------------------------------------- happy path
write <<'YAML'
  - id: a
    title: A
    track: build
    state: next
    seq: 1
    gate: done
    evidence: ~/x
  - id: b
    title: B
    track: build
    state: parked
    resume: later
    evidence: ~/y
YAML
rc="$(run)"
check "valid tracker passes validate"          '[ "$rc" = 0 ]'
check "reports the item count"                 'grep -q "OK — 2 items" "$T/out"'

"$HERE/bin/pa-work" render --file "$W" --out "$T/_Work.md" >/dev/null 2>&1
check "render writes the generated view"       '[ -f "$T/_Work.md" ]'
check "view carries the do-not-edit header"    'grep -q "do not edit this file" "$T/_Work.md"'
check "view surfaces the next item"            'grep -q "NEXT" "$T/_Work.md"'
check "view surfaces parked resume pointer"    'grep -q "resume: later" "$T/_Work.md"'

# ---------------------------------------------------------------- invariant 1
write <<'YAML'
  - id: a
    title: A
    track: build
    state: inflight
    gate: done
    evidence: ~/x
  - id: b
    title: B
    track: build
    state: inflight
    gate: done
    evidence: ~/y
YAML
rc="$(run)"
check "two inflight is rejected"               '[ "$rc" = 1 ]'
check "  ...with the right message"            'grep -q "more than one inflight" "$T/err"'

# ---------------------------------------------------------------- invariant 2
write <<'YAML'
  - id: a
    title: A
    track: build
    state: next
    gate: done
    evidence: ~/x
  - id: b
    title: B
    track: search
    state: next
    gate: done
    evidence: ~/y
YAML
rc="$(run)"
check "two next is rejected"                   'grep -q "more than one next" "$T/err"'

# ---------------------------------------------------------------- invariant 3
write <<'YAML'
  - id: a
    title: A
    track: build
    state: parked
    evidence: ~/x
YAML
rc="$(run)"
check "parked without resume is rejected"      'grep -q "requires .resume." "$T/err"'

# ---------------------------------------------------------------- invariant 4
write <<'YAML'
  - id: a
    title: A
    track: build
    state: queued
    evidence: ~/x
YAML
rc="$(run)"
check "queued without gate is rejected"        'grep -q "requires .gate." "$T/err"'

# ---------------------------------------------------------------- invariant 5
write <<'YAML'
  - id: a
    title: A
    track: build
    state: queued
    seq: 1
    gate: done
    evidence: ~/x
  - id: b
    title: B
    track: build
    state: queued
    seq: 1
    gate: done
    evidence: ~/y
YAML
rc="$(run)"
check "duplicate seq in a track is rejected"   'grep -q "duplicate seq" "$T/err"'

write <<'YAML'
  - id: a
    title: A
    track: build
    state: parked
    seq: 1
    resume: later
    evidence: ~/x
YAML
rc="$(run)"
check "seq on a parked item is rejected"       'grep -q "only allowed on next/queued" "$T/err"'

# ---------------------------------------------------------------- invariant 6
write <<'YAML'
  - id: a
    title: A
    track: build
    state: parked
    resume: later
YAML
rc="$(run)"
check "item without evidence is rejected"      'grep -q "missing .evidence." "$T/err"'

# ---------------------------------------------------------------- invariant 7
write <<'YAML'
  - id: a
    title: A
    track: build
    state: wonder
    evidence: ~/x
YAML
rc="$(run)"
check "unknown state is rejected"              'grep -q "unknown state" "$T/err"'

write <<'YAML'
  - id: a
    title: A
    track: knitting
    state: parked
    resume: later
    evidence: ~/x
YAML
rc="$(run)"
check "unknown track is rejected"              'grep -q "unknown track" "$T/err"'

# ------------------------------------------------------- duplicate ids, exclusions
write <<'YAML'
  - id: a
    title: A
    track: build
    state: parked
    resume: later
    evidence: ~/x
  - id: a
    title: A again
    track: build
    state: parked
    resume: later
    evidence: ~/y
YAML
rc="$(run)"
check "duplicate id is rejected"               'grep -q "duplicate id" "$T/err"'

{ echo "meta:"; echo "  version: 1"
  echo "excluded:"
  echo "  - id: z"
  echo "    title: Z"
  echo "items:"
  echo "  - id: a"
  echo "    title: A"
  echo "    track: build"
  echo "    state: parked"
  echo "    resume: later"
  echo "    evidence: ~/x"
} > "$W"
rc="$(run)"
check "exclusion without reason is rejected"   'grep -q "missing .reason." "$T/err"'
check "excluded rows count toward the guard"   '[ "$rc" = 1 ]'

# ------------------------------------------------------------ parser strictness
printf 'meta:\n\tversion: 1\nitems:\n  - id: a\n' > "$W"
rc="$(run)"
check "tab indentation is rejected"            'grep -q "tab character" "$T/err"'

printf 'meta:\n  version: 1\nitems:\n   - id: a\n' > "$W"
rc="$(run)"
check "odd indentation is rejected"            'grep -q "multiple of 2" "$T/err"'

echo
echo "  $pass passed, $fail failed"
[ "$fail" = 0 ]
